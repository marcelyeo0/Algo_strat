"""Build the "mt5" cost profile from the symbol specifications exported from MT5.

    uv run python -m common.costs.mt5_specs [--export-dir mt5_exports]

writes ``configs/costs/mt5.yaml``: contract sizes, spreads, swaps and triple-swap days come
from the export; values the export cannot provide (commissions, the broker markup of
futures-based CFDs) are copied from the estimates profile and stay marked TODO.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import yaml

from common.costs.model import DAYS_PER_YEAR
from common.data import mt5_loader
from common.data.rates import load_policy_rates
from common.utils.config import load_yaml
from common.utils.paths import configs_dir

# MT5 SYMBOL_SWAP_MODE values used by FTMO (see the MetaTrader 5 documentation).
SWAP_MODE_POINTS = 1
SWAP_MODE_INTEREST_CURRENT = 5


def swap_to_annual_pct(swap: float, mode: int, point: float, price: float) -> float | None:
    """Convert an MT5 swap value into % of notional per year (``None`` for unsupported modes)."""
    if mode == SWAP_MODE_POINTS:
        return swap * point / price * DAYS_PER_YEAR * 100.0
    if mode == SWAP_MODE_INTEREST_CURRENT:
        return swap
    return None


def implied_markup(mode: str, swap_long: float, swap_short: float, r_base: float, r_quote: float) -> float:
    """Broker margin implied by the current MT5 swaps (% per year), prudent side (the larger one).

    rates:        swap_long = (r_b - r_q) - m,  swap_short = (r_q - r_b) - m
    index_rates:  swap_long = -(r_q + m),       swap_short = r_q - m
    """
    if mode == "rates":
        m_long, m_short = (r_base - r_quote) - swap_long, (r_quote - r_base) - swap_short
    elif mode == "index_rates":
        m_long, m_short = -swap_long - r_quote, r_quote - swap_short
    else:
        m_long, m_short = -swap_long, -swap_short
    return max(m_long, m_short, 0.0)


def build_profile(specs: pd.DataFrame, prices: dict[str, float], estimates: dict,
                  current_rates: dict[str, float] | None = None) -> dict:
    """``current_rates``: latest policy rate per currency (% per year), used to calibrate margins."""
    profile = {"profile": "mt5", "defaults": estimates.get("defaults", {}), "instruments": {}}
    for symbol, est in estimates["instruments"].items():
        if symbol not in specs.index:
            continue                    # not offered on the FTMO server: removed from the profile
        spec = dict(est)
        row = specs.loc[symbol]
        spec["contract_size"] = float(row["trade_contract_size"])
        spec["spread"] = float(row["spread"]) * float(row["point"])
        spec["triple_swap_day"] = (int(row["swap_rollover3days"]) - 1) % 7  # MT5: 0 = Sunday
        price = prices.get(symbol)
        if price:
            pct = {side: swap_to_annual_pct(float(row[f"swap_{side}"]), int(row["swap_mode"]), float(row["point"]), price)
                   for side in ("long", "short")}
            if None not in pct.values():
                mode = spec.get("swap_mode", "full")
                if mode == "full":
                    spec["swap_long"], spec["swap_short"] = round(pct["long"], 4), round(pct["short"], 4)
                elif current_rates is not None:
                    rb = current_rates.get(spec.get("base_ccy") or "", 0.0)
                    rq = current_rates.get(spec["quote_ccy"], 0.0)
                    spec["swap_markup"] = round(implied_markup(mode, pct["long"], pct["short"], rb, rq), 4)
        profile["instruments"][symbol] = spec
    return profile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export-dir", type=Path, default=mt5_loader.default_dir())
    args = parser.parse_args()
    specs = mt5_loader.load_specs(args.export_dir)
    if specs is None:
        raise SystemExit(f"No symbol_specs.csv in {args.export_dir}: run `python -m common.data.mt5_export` first.")
    prices = {}
    for symbol in specs.index:
        if mt5_loader.available(symbol, "D1", args.export_dir):
            prices[symbol] = float(mt5_loader.load_rates(symbol, "D1", args.export_dir)["close"].iloc[-1])
    rates = load_policy_rates()
    profile = build_profile(specs, prices, load_yaml("costs/estimates.yaml"), rates.iloc[-1].to_dict())
    header = (
        "# Cost profile \"mt5\", generated by common.costs.mt5_specs from the MT5 export.\n"
        "# Commissions and the markup of futures-based CFDs are copied from the estimates.\n"
        "# TODO: vérifier les commissions et la marge des CFD sur futures\n"
    )
    out = configs_dir() / "costs" / "mt5.yaml"
    out.write_text(header + yaml.safe_dump(profile, sort_keys=False, allow_unicode=True), encoding="utf-8", newline="\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
